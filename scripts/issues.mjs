// 開発課題の記録を検査し、一覧を生成する。本体実装からは利用しない。
// 使い方: node scripts/issues.mjs build | check | new <種類> <題名>
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// プロジェクトに合わせて変える値はここに集める。
export const config = {
  prefix: 'DEV',
  indexTitle: '開発課題',
  kinds: { decision: '設計判断', verification: '調査・検証', bug: '不具合', enhancement: '改善', task: '作業' },
  statuses: { open: '未着手', in_progress: '対応中', deferred: '保留', closed: '完了' },
  resolutions: { resolved: '解決', duplicate: '重複', not_planned: '対応しない' },
  // 以下のパスはリポジトリのルートからの相対パス。
  dir: 'docs/development/issues',
  entryLink: 'README.md',
  rulesLink: 'docs/development/issue-management.md',
};
export const kinds = config.kinds;
export const statuses = config.statuses;
const resolutions = config.resolutions;

// 本文の必須節と、未記入を表す文言。先頭をひな形の初期値に使い、完了した課題に残っていないかを検査する。
const sections = { '課題': [], '完了条件': [], '判断・対応内容': ['未着手。'], '確認結果': ['未実施。', '未確認。'] };
// 保留中の課題だけが持つ節。
const holdSection = '保留';
const marker = '<!-- generated by scripts/issues.mjs; do not edit -->';
// front matter のフィールド。すべて必須で、この順で書き出す。一覧と検査に使う項目だけを置く。
const keys = ['id', 'title', 'kind', 'status', 'recorded_on', 'closed_on', 'resolution', 'duplicate_of', 'depends_on'];
// 生成一覧のファイル名。課題フォルダーの直下に、未完了の一覧と完了年ごとの一覧を置く。
const closedPage = year => `closed-${year}.md`;
const generated = name => name === 'index.md' || /^closed-\d{4}\.md$/.test(name);

const BOM = String.fromCharCode(0xfeff);
const stripBom = s => (s.startsWith(BOM) ? s.slice(1) : s);
const escapeRegExp = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const idPattern = () => new RegExp(`^${escapeRegExp(config.prefix)}-(\\d{4,})$`);
const idNumber = id => Number(id.slice(config.prefix.length + 1));
const formatId = n => `${config.prefix}-${String(n).padStart(4, '0')}`;
// 空ではない1行の文字列か。
const isLine = v => typeof v === 'string' && v.trim() !== '' && !/[\r\n]/.test(v);

function assert(ok, message) {
  if (!ok) throw new Error(message);
}

// dir 配下のファイルを再帰的に列挙する。
function files(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(e => {
    assert(!e.isSymbolicLink(), `シンボリックリンクは扱いません: ${e.name}`);
    const p = path.join(dir, e.name);
    return e.isDirectory() ? files(p) : [p];
  });
}

// ID から、課題フォルダー内の保存先（100件単位のディレクトリ/ID.md）を返す。
export function itemPath(id) {
  const match = idPattern().exec(id);
  assert(match, `不正なID: ${id}`);
  const n = Number(match[1]);
  assert(Number.isSafeInteger(n) && n > 0 && id === formatId(n), `不正なID: ${id}`);
  const start = Math.floor((n - 1) / 100) * 100 + 1;
  const bucket = `${String(start).padStart(4, '0')}-${String(start + 99).padStart(4, '0')}`;
  return `${bucket}/${id}.md`;
}

function validDate(value) {
  return typeof value === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(value)
    && !Number.isNaN(Date.parse(value)) && new Date(value).toISOString().slice(0, 10) === value;
}

// 作業している場所の日付（UTC ではなくローカル時刻）を YYYY-MM-DD で返す。
function today() {
  const d = new Date();
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
}

export function serialize(meta, body) {
  const fields = keys.filter(k => meta[k] !== undefined).map(k => `${k}: ${JSON.stringify(meta[k])}`);
  return `---\n${fields.join('\n')}\n---\n\n${body.trim()}\n`;
}

// front matter の各行（キー: JSON値）を読む。
function readFields(block, filename) {
  const meta = {};
  for (const line of block.split('\n')) {
    const field = /^(\w+): (.+)$/.exec(line);
    assert(field && keys.includes(field[1]) && !Object.hasOwn(meta, field[1]), `不正・重複フィールド: ${filename}: ${line}`);
    try {
      meta[field[1]] = JSON.parse(field[2]);
    } catch {
      throw new Error(`値がJSONではありません: ${filename}: ${line}`);
    }
  }
  assert(keys.every(k => Object.hasOwn(meta, k)), `必須フィールド不足: ${filename}`);
  return meta;
}

// フィールドの値と、状態に応じた組み合わせを検査する。
function checkFields(meta, filename) {
  itemPath(meta.id);
  assert(isLine(meta.title), `題名が不正: ${filename}`);
  assert(Object.hasOwn(kinds, meta.kind) && Object.hasOwn(statuses, meta.status), `種類・状態が不正: ${filename}`);
  assert(validDate(meta.recorded_on), `登録日が不正: ${filename}`);

  // 完了した課題だけが、完了日と完了理由を持つ。
  const closedOk = meta.status === 'closed'
    ? validDate(meta.closed_on) && meta.closed_on >= meta.recorded_on && Object.hasOwn(resolutions, meta.resolution)
    : meta.closed_on === null && meta.resolution === null;
  assert(closedOk, `完了日・完了理由が不正: ${filename}`);

  // 重複で完了した課題だけが、重複先を持つ。
  const duplicateOk = meta.resolution === 'duplicate'
    ? idPattern().test(meta.duplicate_of) && meta.duplicate_of !== meta.id
    : meta.duplicate_of === null;
  assert(duplicateOk, `重複先が不正: ${filename}`);

  // 先行課題は、重複のない自分以外の課題 ID で指定する。
  const deps = meta.depends_on;
  const depsOk = Array.isArray(deps) && deps.every(id => idPattern().test(id) && id !== meta.id)
    && new Set(deps).size === deps.length;
  assert(depsOk, `先行課題が不正: ${filename}`);
}

// 本文から「## 見出し」の節の内容を返す。節がなければ null。
function section(body, heading) {
  const rest = `${body}\n`.split(`\n## ${heading}\n`)[1];
  return rest === undefined ? null : rest.split('\n## ')[0].trim();
}

// 本文の題名・必須節と、状態に応じた節の内容を検査する。
function checkBody(meta, body, filename) {
  assert(body.startsWith(`# ${meta.id} ${meta.title}\n`), `題名とメタデータが不一致: ${filename}`);
  for (const heading of Object.keys(sections)) {
    assert(section(body, heading) !== null, `必須節がありません: ${filename}: ${heading}`);
  }
  // 記入済みか（空でも、未記入を表す文言のままでもない）。
  const filled = heading => !['', ...sections[heading]].includes(section(body, heading));

  // 完了した課題は対応内容（重複・対応しない場合はその理由）を持ち、解決の場合は確認結果も持つ。
  if (meta.status === 'closed') {
    assert(filled('判断・対応内容'), `判断・対応内容がありません: ${filename}`);
    if (meta.resolution === 'resolved') assert(filled('確認結果'), `完了根拠がありません: ${filename}`);
  }

  // 保留中の課題だけが、保留の節（理由・影響・解消条件）を持つ。
  const hold = section(body, holdSection);
  assert(meta.status === 'deferred' ? Boolean(hold) : hold === null, `保留の節が不正: ${filename}`);
}

export function parse(text, filename) {
  text = stripBom(text).replaceAll('\r\n', '\n');
  const match = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(text);
  assert(match, `メタデータがありません: ${filename}`);
  const meta = readFields(match[1], filename);
  checkFields(meta, filename);
  const body = match[2].trim();
  checkBody(meta, body, filename);
  return { ...meta, body, filename };
}

// 課題フォルダー（root）の全課題を読み、配置・ID・重複先を検査する。
export function load(root) {
  const entries = fs.readdirSync(root, { withFileTypes: true });
  // 読み込まない場所に置かれた課題を見落とさないよう、想定外の項目は拒否する。
  for (const e of entries) {
    const known = e.name.startsWith('.') || generated(e.name) || /^\d+-\d+$/.test(e.name);
    assert(known, `課題はIDの100件単位のディレクトリへ配置してください: ${e.name}`);
  }
  const paths = entries.filter(e => /^\d+-\d+$/.test(e.name)).flatMap(e => {
    assert(e.isDirectory() && !e.isSymbolicLink(), `課題の配置が不正: ${e.name}`);
    return files(path.join(root, e.name));
  });
  const issues = paths.map(p => {
    assert(p.endsWith('.md'), `課題以外のファイル: ${p}`);
    const issue = parse(fs.readFileSync(p, 'utf8'), p);
    assert(path.resolve(root, itemPath(issue.id)) === path.resolve(p), `保存先がIDと不一致: ${p}`);
    return issue;
  }).sort((a, b) => idNumber(a.id) - idNumber(b.id));

  const ids = new Set();
  for (const issue of issues) {
    assert(!ids.has(issue.id), `ID重複: ${issue.id}`);
    ids.add(issue.id);
  }
  for (const issue of issues) {
    if (issue.duplicate_of) assert(ids.has(issue.duplicate_of), `重複先が存在しません: ${issue.id}`);
    assert(issue.depends_on.every(id => ids.has(id)), `先行課題が存在しません: ${issue.id}`);
  }

  // 先行関係をたどって自分へ戻る課題があれば、どれも着手できないので拒否する。
  const byId = new Map(issues.map(i => [i.id, i]));
  const done = new Set();
  const visit = (id, trail) => {
    if (done.has(id)) return;
    assert(!trail.includes(id), `先行関係が循環しています: ${[...trail, id].join(' → ')}`);
    for (const next of byId.get(id).depends_on) visit(next, [...trail, id]);
    done.add(id);
  };
  for (const issue of issues) visit(issue.id, []);
  return issues;
}

function escapeCell(value) {
  return String(value)
    .replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;')
    .replaceAll('|', '&#124;').replaceAll('[', '&#91;').replaceAll(']', '&#93;');
}
function doc(title, body) {
  return `${marker}\n\n# ${title}\n\n${body}\n`;
}
// 生成一覧はすべて課題フォルダーの直下に置くので、課題へのリンクは itemPath のままでよい。
const link = id => `[${id}](${itemPath(id)})`;
// 生成一覧から、リポジトリのルートからの相対パス target へのリンク。
function fromRoot(target) {
  return path.posix.relative(config.dir, target);
}

// open は未完了の課題 ID の集合。未完了の一覧で、まだ終わっていない先行課題を示すのに使う。
function table(list, closed, open) {
  if (!list.length) return '該当する課題はありません。';
  const header = closed ? ['ID', '課題', '種類', '完了理由', '完了日'] : ['ID', '課題', '種類', '状態', '先行（未完了）', '登録日'];
  const reason = i => resolutions[i.resolution] + (i.duplicate_of ? `（${link(i.duplicate_of)}）` : '');
  const waiting = i => i.depends_on.filter(id => open.has(id)).map(link).join('、');
  const rows = list.map(i => [
    link(i.id),
    escapeCell(i.title),
    kinds[i.kind],
    ...(closed ? [reason(i), i.closed_on] : [statuses[i.status], waiting(i), i.recorded_on]),
  ]);
  return [header, header.map(() => '---'), ...rows].map(cells => `| ${cells.join(' | ')} |`).join('\n');
}

// 生成する一覧を、ファイル名（課題フォルダーの直下）→ 内容の Map で返す。
export function indexes(issues) {
  const out = new Map();
  // 完了の一覧（完了年ごとに1ページ）。新しい年から並べる。
  const closed = issues.filter(i => i.status === 'closed');
  const years = [...new Set(closed.map(i => i.closed_on.slice(0, 4)))].sort().reverse();
  const yearPages = years.map(year => {
    const list = closed.filter(i => i.closed_on.startsWith(year))
      .sort((a, b) => b.closed_on.localeCompare(a.closed_on) || idNumber(a.id) - idNumber(b.id));
    const content = doc(`${config.indexTitle}：${year}年の完了`, [
      '[未完了一覧へ戻る](index.md)',
      `${list.length}件。`,
      table(list, true),
    ].join('\n\n'));
    return { name: closedPage(year), content, link: `[${year}年](${closedPage(year)})（${list.length}件）` };
  });

  // 未完了の一覧（1ページ）。課題の入口として、完了年ごとの一覧へのリンクも置く。
  const active = issues.filter(i => i.status !== 'closed');
  const counts = Object.entries(statuses).filter(([key]) => key !== 'closed')
    .map(([key, label]) => `${label}${active.filter(i => i.status === key).length}件`).join('、');
  out.set('index.md', doc(`${config.indexTitle}：未完了`, [
    `[README](${fromRoot(config.entryLink)})・[管理ルール](${fromRoot(config.rulesLink)})`,
    `${active.length}件。${counts}。`,
    `完了${closed.length}件。${yearPages.map(page => page.link).join('・')}`,
    table(active, false, new Set(active.map(i => i.id))),
  ].join('\n\n')));
  for (const page of yearPages) out.set(page.name, page.content);
  return out;
}

// 一覧を再生成する。check が true なら書き換えず、一覧が最新でなければ失敗する。
export function build(root, check = false) {
  const issues = load(root);
  const expected = indexes(issues);
  const exists = name => fs.existsSync(path.join(root, name));
  const read = name => fs.readFileSync(path.join(root, name), 'utf8');

  // 生成先にあるが、今回の一覧には含まれない古いページ。
  const stale = fs.readdirSync(root).filter(name => generated(name) && !expected.has(name));
  for (const name of [...expected.keys(), ...stale]) {
    if (exists(name)) assert(read(name).startsWith(marker), `手書きファイルを上書きできません: ${name}`);
  }
  const changed = [...expected].filter(([name, content]) => !exists(name) || read(name).replaceAll('\r\n', '\n') !== content);

  if (check) {
    assert(!changed.length && !stale.length, `索引が未更新: ${[...changed.map(([name]) => name), ...stale].join(', ')}`);
    return issues.length;
  }
  for (const [name, content] of changed) {
    fs.writeFileSync(path.join(root, name), content);
  }
  for (const name of stale) fs.unlinkSync(path.join(root, name));
  return issues.length;
}

// 最大 ID の次を採番して課題のひな形を作り、一覧を再生成する。
export function create(root, kind, title) {
  assert(Object.hasOwn(kinds, kind) && isLine(title), '種類と1行の題名を指定してください');
  const issues = load(root);
  const id = formatId(Math.max(0, ...issues.map(i => idNumber(i.id))) + 1);
  const meta = {
    id, title, kind, status: 'open', recorded_on: today(), closed_on: null, resolution: null, duplicate_of: null,
    depends_on: [],
  };
  // 種類ごとに、「課題」の節へ書き足す内容。
  const prompts = {
    bug: '\n再現手順・期待結果・実際の結果と、分かっている範囲で影響する版を記入する。',
    task: '\n対応する要件・設計へのリンクと、作る成果物（設計文書・コードなど）を記入する。',
  };
  const body = [
    `# ${id} ${title}`,
    `## 課題\n\n問題・背景・対象範囲を記入する。${prompts[kind] ?? ''}`,
    '## 完了条件\n\n- 完了を判断できる条件を記入する。',
    ...['判断・対応内容', '確認結果'].map(heading => `## ${heading}\n\n${sections[heading][0]}`),
  ].join('\n\n');
  const p = path.join(root, itemPath(id));
  fs.mkdirSync(path.dirname(p), { recursive: true });
  // 同じ ID のファイルが既にあれば、上書きせずに失敗する。
  fs.writeFileSync(p, serialize(meta, body), { flag: 'wx' });
  build(root);
  return itemPath(id);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', config.dir);
    const [command, kind, ...title] = process.argv.slice(2);
    if (command === 'new') console.log(create(root, kind, title.join(' ')));
    else if (command === 'build' || command === 'check') console.log(`${command}: ${build(root, command === 'check')}件`);
    else throw new Error('使い方: node scripts/issues.mjs build | check | new <種類> <題名>');
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
